// Regenerate standalone method skills from the toolkit. Run from the repository root.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

const generatedMarker = "<!-- Generated by scripts/generate-structured-thinking.go; edit the toolkit sources. -->"

func section(source, heading string) (string, error) {
	start := strings.Index(source, "## "+heading+"\n")
	if start < 0 {
		return "", fmt.Errorf("missing section %q", heading)
	}
	part := source[start:]
	if end := strings.Index(part[3:], "\n## "); end >= 0 {
		part = part[:end+3]
	}
	return strings.TrimSpace(part) + "\n", nil
}

func generate(root string, check bool) error {
	base := filepath.Join(root, "skills", "structured-thinking")
	source, err := os.ReadFile(filepath.Join(base, "SKILL.md"))
	if err != nil {
		return err
	}
	var shared strings.Builder
	for _, heading := range []string{"Evidence and scope", "Return a useful result", "Method provenance"} {
		part, err := section(string(source), heading)
		if err != nil {
			return err
		}
		shared.WriteString("\n" + part)
	}
	rows := regexp.MustCompile(`(?m)^\| ([^|]+) \| \[([^\]]+)\]\(references/([a-z0-9-]+)\.md\) \|$`).FindAllStringSubmatch(string(source), -1)
	guides, err := filepath.Glob(filepath.Join(base, "references", "*.md"))
	if err != nil {
		return err
	}
	if len(rows) != 25 || len(guides) != 25 {
		return fmt.Errorf("expected 25 routed methods and guides, got %d and %d", len(rows), len(guides))
	}
	outputs := make(map[string][]byte)
	for _, row := range rows {
		slug := row[3]
		if slug == "six-thinking-hats" {
			slug = "six-hats"
		}
		name := "st-" + slug
		path := filepath.Join(root, "skills", name, "SKILL.md")
		if _, exists := outputs[path]; exists {
			return fmt.Errorf("duplicate method %s", name)
		}
		guide, err := os.ReadFile(filepath.Join(base, "references", row[3]+".md"))
		if err != nil {
			return err
		}
		if !bytes.HasPrefix(guide, []byte("# ")) {
			return fmt.Errorf("missing guide title: %s", row[3])
		}
		description := fmt.Sprintf("Apply %s to %s. Use when this method is requested or fits that task; skip routine edits and simple factual answers.", row[2], strings.ToLower(row[1][:1])+row[1][1:])
		content := fmt.Sprintf("---\nname: %s\ndescription: %q\nlicense: MIT\nmetadata:\n  author: jadmadi\n---\n\n%s\n\n", name, description, generatedMarker)
		content += "# " + row[2] + "\n\n"
		content += "Apply this method directly to the supplied task. Identify the desired result,\nconstraints, and available evidence. Ask for missing information only if it could\nchange the result; otherwise state assumptions or give a conditional answer.\nIf this method is a poor fit, explain why and suggest a better fit without silently\nreplacing the user's choice. Stop when a supported action or specific uncertainty\nis clear. This skill is self-contained; no other skill or reference file is needed.\n\n"
		// Preserve the canonical method body verbatim, excluding its duplicated title.
		_, body, _ := strings.Cut(string(guide), "\n")
		content += strings.TrimLeft(body, "\n") + shared.String()
		outputs[path] = []byte(content)
	}
	// Validate all sources and destinations before writing any files.
	for path, content := range outputs {
		old, err := os.ReadFile(path)
		if err != nil && !os.IsNotExist(err) {
			return err
		}
		if check {
			if !bytes.Equal(old, content) {
				return fmt.Errorf("missing or stale generated skill: %s", path)
			}
		} else if err == nil && !bytes.Contains(old, []byte(generatedMarker)) {
			return fmt.Errorf("refusing to overwrite unmanaged skill: %s", path)
		}
	}
	if !check {
		for path, content := range outputs {
			if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
				return err
			}
			if err := os.WriteFile(path, content, 0644); err != nil {
				return err
			}
		}
	}
	fmt.Printf("OK: 25 standalone method skills (check=%t)\n", check)
	return nil
}

func main() {
	check := flag.Bool("check", false, "fail if generated skills are missing or stale; write nothing")
	root := flag.String("root", ".", "repository root")
	flag.Parse()
	if err := generate(*root, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
